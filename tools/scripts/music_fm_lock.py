"""#69 固定 FM 擷取／封裝資料與 Go 表格；來源原版唯讀，不保存素材本體。

入口與使用邊界：docs/spec/071-native-fm-import.md、074-cross-platform-fm-pcm.md。
產物 docs/internals/data/fm-import-lock.json，以及 workplace/music69-fm/fmdata.go。
Go 表格是 JSON 的生成副本，必須一起更新與核對，不手改。
"""
from pathlib import Path
import hashlib
import json
import os
import struct
import wave

root = Path('/ref')
out = Path('/work/workplace/music69-fm')
out.mkdir(exist_ok=True)
targets = [Path('/work/docs/internals/data/fm-import-lock.json'), out/'fmdata.go']
for target in targets:
    for p in (target.parent, *([target] if target.exists() else [])):
        assert (p.stat().st_uid, p.stat().st_gid) == (os.getuid(), os.getgid())


def sha(p):
    with p.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


head = 'f7523f9ac7ed6f17bc4e37686b10748c5e9bf89c'
doc = {'probe_head': head, 'executables': {name: sha(Path('/orig')/name) for name in ['GIN3.COM', 'GIN3PS.EXE', 'OPEN.EXE', 'ENDING.EXE']}, 'tracks': {}}
lines = (root/'assets/original/music/ogg/SOURCES.tsv').read_text().splitlines()[1:]
baseline = Path('/work/workplace/music69-windows/linux-pcm-baseline')
assert baseline.is_dir(), '缺規格 074 的十一首無損基準，不生成較弱的鎖'
expected_tools = {
    '/usr/local/bin/opl2wav': 'fd7864ccb7cd1eeac5f56bd3ca4bdcf23750f59bb6f03eb66d258a11d15ab8e1',
    '/usr/bin/ffmpeg': '0dafc1360bb07743f76abeb1e4ae16b0aaa1331e9041a0e8d6a8524111dc0cbb',
}
actual_tools = {line.split()[1]: line.split()[0] for line in (baseline/'tools.sha256').read_text().splitlines()}
assert actual_tools == expected_tools, '基準合成工具身份改變，先重審規格'
assert len(list(baseline.glob('*.wav'))) == len(list(baseline.glob('*.f32'))) == 11
doc['pcm_baseline'] = {
    'image': 'sha256:da8c479c3466feed5cd363ed439b064303d68c9789abc02a37fb09560285b126',
    'tools': (baseline/'tools.sha256').read_text(),
    'ffmpeg_version': (baseline/'ffmpeg-version.txt').read_text(),
    'script_sha256': sha(Path('/work/tools/scripts/music_fm_pcm_baseline.sh')),
    'format': 'stereo f32le, 44100 Hz, volume=-1.00dB',
    'gate': 'VGM／WAV／增益後 PCM 相同；平台 OGG 差異經使用者於 2026-10-01 允許',
}
for line in lines:
    name, route, gain, source, vgm, ogg, old = line.split('\t')
    raw = (root/'assets/original/music/ogg'/(name+'.ogg')).read_bytes()
    assert sha(root/'assets/original/music/vgm'/(name+'.vgm')) == vgm
    assert hashlib.sha256(raw).hexdigest() == ogg
    assert sha(Path('/orig')/(name+'.MDS')) == source
    assert gain == '-1.00'
    assert sha(Path('/work/workplace/music69-fm/full')/(name+'.vgm')) == vgm
    with wave.open(str(baseline/(name+'.wav'))) as w:
        assert w.getframerate() == 44100 and w.getnchannels() == 2 and w.getsampwidth() == 2
        assert (baseline/(name+'.f32')).stat().st_size == w.getnframes()*8
    doc['tracks'][name] = {'source_sha256': source, 'vgm_sha256': vgm, 'ogg_sha256': ogg,
        'wav_sha256': sha(baseline/(name+'.wav')), 'pcm_sha256': sha(baseline/(name+'.f32')),
        'serial': struct.unpack_from('<I', raw, 14)[0], 'gain_db': gain, 'route': route, 'historical_probe_head': old}
Path('/work/docs/internals/data/fm-import-lock.json').write_text(json.dumps(doc, ensure_ascii=False, indent=2)+'\n')
go = '// Code generated by tools/scripts/music_fm_lock.py; DO NOT EDIT.\n// 權威資料：docs/internals/data/fm-import-lock.json（規格 071／074）。\npackage main\n\n'
go += 'const fmProbeHead = "'+head+'"\n\n'
go += 'var fmExecutableHashes = map[string]string{\n'+''.join('\t'+json.dumps(k)+': '+json.dumps(v)+',\n' for k,v in doc['executables'].items())+'}\n\n'
go += 'var fmLocks = map[string]fmLock{\n'
for name, t in doc['tracks'].items():
    fields = ['source_sha256', 'vgm_sha256', 'ogg_sha256', 'wav_sha256', 'pcm_sha256']
    go += '\t'+json.dumps(name)+': {'+', '.join(json.dumps(t[x]) for x in fields)+', '+str(t['serial'])+', '+json.dumps(t['gain_db'])+', '+json.dumps(t['route'])+'},\n'
go += '}\n'
(out/'fmdata.go').write_text(go)
print('已驗原始／VGM／OGG 並產生封裝鎖定資料。')
