"""#69 固定 FM 擷取／封裝資料與 Go 表格；來源原版唯讀，不保存素材本體。

入口與使用邊界：docs/spec/071-native-fm-import.md。
產物 docs/internals/data/fm-import-lock.json，以及 workplace/music69-fm/fmdata.go。
Go 表格是 JSON 的生成副本，必須一起更新與核對，不手改。
"""
from pathlib import Path
import hashlib
import json
import os
import struct

root = Path('/ref')
out = Path('/work/workplace/music69-fm')
out.mkdir(exist_ok=True)
targets = [Path('/work/docs/internals/data/fm-import-lock.json'), out/'fmdata.go']
for target in targets:
    for p in (target.parent, *([target] if target.exists() else [])):
        assert (p.stat().st_uid, p.stat().st_gid) == (os.getuid(), os.getgid())


def sha(p):
    with p.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


head = 'f7523f9ac7ed6f17bc4e37686b10748c5e9bf89c'
doc = {'probe_head': head, 'executables': {name: sha(Path('/orig')/name) for name in ['GIN3.COM', 'GIN3PS.EXE', 'OPEN.EXE', 'ENDING.EXE']}, 'tracks': {}}
lines = (root/'assets/original/music/ogg/SOURCES.tsv').read_text().splitlines()[1:]
for line in lines:
    name, route, gain, source, vgm, ogg, old = line.split('\t')
    raw = (root/'assets/original/music/ogg'/(name+'.ogg')).read_bytes()
    assert sha(root/'assets/original/music/vgm'/(name+'.vgm')) == vgm
    assert hashlib.sha256(raw).hexdigest() == ogg
    assert sha(Path('/orig')/(name+'.MDS')) == source
    doc['tracks'][name] = {'source_sha256': source, 'vgm_sha256': vgm, 'ogg_sha256': ogg, 'serial': struct.unpack_from('<I', raw, 14)[0], 'gain_db': gain, 'route': route, 'historical_probe_head': old}
Path('/work/docs/internals/data/fm-import-lock.json').write_text(json.dumps(doc, ensure_ascii=False, indent=2)+'\n')
go = '// Code generated by tools/scripts/music_fm_lock.py; DO NOT EDIT.\n// 權威資料：docs/internals/data/fm-import-lock.json（規格 071）。\npackage main\n\n'
go += 'const fmProbeHead = "'+head+'"\n\n'
go += 'var fmExecutableHashes = map[string]string{\n'+''.join('\t'+json.dumps(k)+': '+json.dumps(v)+',\n' for k,v in doc['executables'].items())+'}\n\n'
go += 'var fmLocks = map[string]fmLock{\n'
for name, t in doc['tracks'].items():
    fields = ['source_sha256', 'vgm_sha256', 'ogg_sha256']
    go += '\t'+json.dumps(name)+': {'+', '.join(json.dumps(t[x]) for x in fields)+', '+str(t['serial'])+', '+json.dumps(t['gain_db'])+', '+json.dumps(t['route'])+'},\n'
go += '}\n'
(out/'fmdata.go').write_text(go)
print('已驗原始／VGM／OGG 並產生封裝鎖定資料。')
